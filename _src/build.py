#!/usr/bin/env python3
"""Builds the essay pages, the Texts list, sitemap.xml, feed.xml and robots.txt.

    python3 _src/build.py

Source of truth: _src/essays/<slug>.md  (plain text, see _src/README.md).
Standard library only. The home page and the 404 page are written by hand.
"""
import datetime
import html
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = "https://markmukhin.com"
NAME = "Mark Mukhin"
LIST_DESC = "Long-form writing on systems, patterns, and what's underneath."
OG_IMAGE = SITE + "/og.png"
SPIRAL_BASE_TURNS = 2  # the spiral has this many turns, plus one per essay
FOOTER_TEXT = "Berlin — 2026"
GENERATED = "<!-- generated by _src/build.py from _src/essays/ — edit the source, not this file -->"

# ------------------------------------------------------------------ pieces


def sparkle(cx, cy, r, k=0.2):
    """A four-point star with slightly concave sides."""
    k *= r
    f = lambda v: f"{v:.1f}"
    return (
        f"M{f(cx)},{f(cy - r)} Q{f(cx + k)},{f(cy - k)} {f(cx + r)},{f(cy)} "
        f"Q{f(cx + k)},{f(cy + k)} {f(cx)},{f(cy + r)} "
        f"Q{f(cx - k)},{f(cy + k)} {f(cx - r)},{f(cy)} "
        f"Q{f(cx - k)},{f(cy - k)} {f(cx)},{f(cy - r)} Z"
    )


BREAK_SVG = (
    '      <div class="break" role="separator" aria-hidden="true">\n'
    '        <svg viewBox="0 0 44 38">'
    + "".join(f'<path pathLength="1" d="{sparkle(*c)}"/>' for c in [(22, 9, 8), (9.5, 29, 8), (34.5, 29, 8)])
    + "</svg>\n      </div>"
)

END_MARK = (
    '      <div class="end-mark" aria-hidden="true">'
    '<svg viewBox="0 0 12 12"><path d="M6 .5 11.5 6 6 11.5.5 6Z"/></svg></div>'
)

LINKS_ROW = (
    '<a href="https://www.linkedin.com/in/markmukhin/">LinkedIn</a>\n'
    '        <span class="sep">/</span>\n'
    '        <a href="https://www.are.na/nku-nku-x2">Are.na</a>\n'
    '        <span class="sep">/</span>\n'
    '        <a href="https://x.com/nkunkux2">X</a>'
)


def esc(s):
    return html.escape(s, quote=True)


def inline(text):
    """Plain text -> HTML. Supports [text](url) links; everything else is escaped."""
    text = html.escape(text, quote=False)
    return re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+|/[^)\s]*)\)", r'<a href="\2">\1</a>', text)


def display_date(d):
    return d.strftime("%d.%m.%Y")


# ------------------------------------------------------------------ sources


def parse_body(text):
    blocks = []
    for chunk in re.split(r"\n\s*\n", text.strip()):
        chunk = " ".join(line.strip() for line in chunk.splitlines()).strip()
        if not chunk:
            continue
        if chunk == "* * *":
            blocks.append(("break", ""))
        elif chunk.startswith("## "):
            blocks.append(("h2", chunk[3:].strip()))
        else:
            blocks.append(("p", chunk))
    return blocks


CURLY = {"\u201c": '"', "\u201d": '"', "\u2018": "'", "\u2019": "'"}


def straighten(text):
    """Curly quotes -> straight ones (the site uses straight). Returns (text, count)."""
    count = sum(text.count(c) for c in CURLY)
    return text.translate(str.maketrans(CURLY)), count


def load_essays():
    essays = []
    for path in sorted((ROOT / "_src" / "essays").glob("*.md")):
        source, curly = straighten(path.read_text(encoding="utf-8"))
        if curly:
            print(f"straightened {curly} curly quote(s) in {path.name}")
        m = re.match(r"---\n(.*?)\n---\n(.*)", source, re.S)
        if not m:
            sys.exit(f"{path.name}: missing --- front matter ---")
        meta = {}
        for line in m.group(1).splitlines():
            key, _, value = line.partition(":")
            meta[key.strip()] = value.strip()
        for key in ("title", "date", "description"):
            if not meta.get(key):
                sys.exit(f"{path.name}: front matter needs '{key}'")
        essays.append(
            {
                "slug": path.stem,
                "title": meta["title"],
                "description": meta["description"],
                "date": datetime.date.fromisoformat(meta["date"]),
                "blocks": parse_body(m.group(2)),
            }
        )
    essays.sort(key=lambda e: e["date"], reverse=True)
    return essays


# ------------------------------------------------------------------ page shell


def head(*, title, description, path, og_type, og_title=None, published=None):
    url = SITE + path
    og_title = og_title or title
    extra = f'  <meta property="article:published_time" content="{published}">\n' if published else ""
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <meta name="color-scheme" content="light dark">
  <title>{esc(title)}</title>
  <meta name="description" content="{esc(description)}">
  <link rel="canonical" href="{url}">
  <meta property="og:site_name" content="{NAME}">
  <meta property="og:title" content="{esc(og_title)}">
  <meta property="og:description" content="{esc(description)}">
  <meta property="og:type" content="{og_type}">
  <meta property="og:url" content="{url}">
  <meta property="og:image" content="{OG_IMAGE}">
{extra}  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="{esc(og_title)}">
  <meta name="twitter:description" content="{esc(description)}">
  <meta name="twitter:image" content="{OG_IMAGE}">
  <link rel="icon" type="image/x-icon" href="/favicon.ico">
  <link rel="icon" type="image/png" sizes="32x32" href="/favicon-32.png">
  <link rel="apple-touch-icon" href="/apple-touch-icon.png">
  <link rel="alternate" type="application/atom+xml" title="{NAME}" href="/feed.xml">
  <link rel="preload" href="/assets/fonts/JetBrainsMono-Regular.woff" as="font" type="font/woff" crossorigin>
  <link rel="preload" href="/assets/fonts/JetBrainsMono-Bold.woff" as="font" type="font/woff" crossorigin>
  <link rel="stylesheet" href="/assets/style.css">
  <script src="/assets/site.js" defer></script>
</head>
"""


TOP_BAR = f"""    <header class="fade-in">
      <div class="top-bar">
        <a href="/">{NAME}</a>
        <nav>
          <a href="/texts/" class="active">Texts</a>
        </nav>
      </div>
    </header>
"""

FOOTER = f"""    <footer>
      <span>{FOOTER_TEXT}</span>
      <span>·</span>
      <a href="/feed.xml">RSS</a>
    </footer>
"""


def render_blocks(blocks):
    out = []
    for kind, text in blocks:
        if kind == "break":
            out.append(BREAK_SVG)
        elif kind == "h2":
            out.append(f"      <h2>{inline(text)}</h2>")
        else:
            out.append(f"      <p>{inline(text)}</p>")
    return "\n\n".join(out)


def essay_page(e):
    iso = e["date"].isoformat()
    return (
        head(
            title=f"{e['title']} — {NAME}",
            og_title=e["title"],
            description=e["description"],
            path=f"/texts/{e['slug']}/",
            og_type="article",
            published=iso,
        )
        + f"""<body data-spiral="scroll">
  {GENERATED}
  <div class="container">

{TOP_BAR}
    <div class="article-header fade-in d1">
      <a href="/texts/" class="back-link">All texts</a>
      <h1 class="article-title">{inline(e['title'])}</h1>
      <div class="article-date"><time datetime="{iso}">{display_date(e['date'])}</time></div>
    </div>

    <article class="article-body fade-in d1">

{render_blocks(e['blocks'])}

{END_MARK}

    </article>

    <div class="end-links fade-in d1">
      <a href="/texts/">← All texts</a>
      <div class="links">
        {LINKS_ROW}
      </div>
    </div>

{FOOTER}
  </div>
</body>
</html>
"""
    )


def list_page(essays):
    items = "\n".join(
        f"""      <li class="post-item">
        <div class="post-date"><time datetime="{e['date'].isoformat()}">{display_date(e['date'])}</time></div>
        <div class="post-title"><a href="/texts/{e['slug']}/">{inline(e['title'])}</a></div>
        <div class="post-excerpt">{inline(e['description'])}</div>
      </li>"""
        for e in essays
    )
    return (
        head(title=f"Texts — {NAME}", og_title="Texts", description=LIST_DESC, path="/texts/", og_type="website")
        + f"""<body data-spiral="small">
  {GENERATED}
  <div class="container">

{TOP_BAR}
    <h1 class="page-title fade-in d1">Texts</h1>

    <ul class="post-list fade-in d2">
{items}
    </ul>

{FOOTER}
  </div>
</body>
</html>
"""
    )


# ------------------------------------------------------------------ feeds


def feed_html(blocks):
    out = []
    for kind, text in blocks:
        if kind == "break":
            out.append("<hr/>")
        elif kind == "h2":
            out.append(f"<h2>{inline(text)}</h2>")
        else:
            out.append(f"<p>{inline(text)}</p>")
    return "\n".join(out)


def atom(essays):
    stamp = lambda d: f"{d.isoformat()}T00:00:00Z"
    updated = stamp(max(e["date"] for e in essays))
    entries = "".join(
        f"""  <entry>
    <title>{esc(e['title'])}</title>
    <link href="{SITE}/texts/{e['slug']}/"/>
    <id>{SITE}/texts/{e['slug']}/</id>
    <published>{stamp(e['date'])}</published>
    <updated>{stamp(e['date'])}</updated>
    <summary>{esc(e['description'])}</summary>
    <content type="html">{esc(feed_html(e['blocks']))}</content>
  </entry>
"""
        for e in essays
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<feed xmlns="http://www.w3.org/2005/Atom">
  <title>{NAME} — Texts</title>
  <subtitle>{esc(LIST_DESC)}</subtitle>
  <link href="{SITE}/feed.xml" rel="self"/>
  <link href="{SITE}/texts/"/>
  <id>{SITE}/texts/</id>
  <updated>{updated}</updated>
  <author><name>{NAME}</name></author>
{entries}</feed>
"""


def sitemap(essays):
    urls = [(f"{SITE}/", None), (f"{SITE}/texts/", None)] + [
        (f"{SITE}/texts/{e['slug']}/", e["date"].isoformat()) for e in essays
    ]
    body = "".join(
        f"  <url><loc>{u}</loc>" + (f"<lastmod>{m}</lastmod>" if m else "") + "</url>\n" for u, m in urls
    )
    return f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n{body}</urlset>\n'


# ------------------------------------------------------------------ main


HAND_WRITTEN = {"index.html", "404.html"}  # never generated


def write(rel, text):
    if rel in HAND_WRITTEN:
        sys.exit(f"refusing to overwrite hand-written {rel}")
    path = ROOT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print("wrote", rel)


def main():
    essays = load_essays()
    if not essays:
        sys.exit("no essays found in _src/essays/")
    for e in essays:
        write(f"texts/{e['slug']}/index.html", essay_page(e))
    write("texts/index.html", list_page(essays))
    write("feed.xml", atom(essays))
    write("sitemap.xml", sitemap(essays))
    write("robots.txt", f"User-agent: *\nAllow: /\n\nSitemap: {SITE}/sitemap.xml\n")

    # the spiral gets one more turn with every essay
    js = ROOT / "assets" / "site.js"
    turns = SPIRAL_BASE_TURNS + len(essays)
    src = js.read_text(encoding="utf-8")
    new, n = re.subn(r"var TURNS = \d+;", f"var TURNS = {turns};", src, count=1)
    if n != 1:
        sys.exit("could not find 'var TURNS = N;' in assets/site.js")
    js.write_text(new, encoding="utf-8")
    print(f"spiral: {turns} turns ({len(essays)} essays)")


if __name__ == "__main__":
    main()
